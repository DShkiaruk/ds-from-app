#!/usr/bin/env node
// extraction/tokens.json (+ the designer's decisions) -> the token layer every style in this repo reads:
//   src/tokens/<group>.css   one custom property per token, its label and evidence in a comment
//   src/tokens/canvas.css    the product's own page background, text colour and font (<body> as measured)
//   src/tokens/fonts.css     the web fonts the app loads (font-service @imports, declared @font-face), when recorded
//   src/tokens/index.css     imports them all
//   src/tokens/tokens.json   the same, compact, for Storybook's Foundations pages and the gates
//   src/foundations/Foundations.stories.tsx   one story per group that exists
// Generated — never edit them: `npm run check:tokens` fails on a hand edit. A new value goes into
// extraction/canon/decided.tokens.json (label decided, dated reason; read here, it replaces a derived or decided value and never a measured one); then `npm run tokens`.
import { existsSync, mkdirSync, readdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseColor, toHex } from './lib/color.mjs';

const EXT = 'co.eleken.ds';
export const HEADER = '/* Generated by tools/tokens-css.mjs — do not edit (npm run check:tokens) */';
const GROUP_OF = { color: 'color', spacing: 'space', fontSize: 'type', lineHeight: 'type', fontWeight: 'type', fontFamily: 'type', letterSpacing: 'type', radius: 'radius', shadow: 'shadow', borderWidth: 'border', duration: 'motion', easing: 'motion' };
const GROUPS = ['color', 'space', 'type', 'radius', 'shadow', 'border', 'motion', 'other'];
const STORY = { color: 'Colors', space: 'Spacing', type: 'Typography', radius: 'Radius', shadow: 'Shadows', border: 'Borders', motion: 'Motion', other: 'Other' };

// What a colour paints: its usage properties folded into text / background / border / icon (fill, stroke); any other
// property (box-shadow, ...) is only listed as "also". The group of the most-painted kind wins (ties: the order here).
const PAINT_ORDER = ['text', 'background', 'border', 'icon'];
const PAINT_LABEL = { text: 'text', background: 'background', border: 'border', icon: 'fill/stroke' };
const paintKind = (prop) => (/^background(-color|-image)?$/.test(prop) ? 'background' : /^(border|outline)/.test(prop) ? 'border' : /^(fill|stroke)$/.test(prop) ? 'icon' : /^(color|text-decoration-color|caret-color)$/.test(prop) ? 'text' : null);
export function paintOf(props, evidence = '') {
  const tally = new Map();
  for (const [prop, n] of Object.entries(props ?? {})) { const k = paintKind(prop) ?? prop; tally.set(k, (tally.get(k) ?? 0) + Number(n || 0)); }
  if (tally.size) {
    const main = PAINT_ORDER.filter((k) => tally.has(k)).sort((a, b) => tally.get(b) - tally.get(a));
    const paint = main[0] ?? 'other';
    const also = [...tally].filter(([k]) => k !== paint).sort((a, b) => b[1] - a[1]).map(([k, n]) => `${PAINT_LABEL[k] ?? k} ×${n}`);
    return { paint, also };
  }
  // a derived colour carries no counts, only its evidence "(as stroke, focus-visible outline)": the roles it names, first = primary
  const named = /\(as ([^)]+)\)/.exec(evidence)?.[1];
  const kinds = (named ? named.split(',').map((x) => (/background/.test(x) ? 'background' : /border|outline/.test(x) ? 'border' : /stroke|fill/.test(x) ? 'icon' : /text|color/.test(x) ? 'text' : null)) : []).filter(Boolean);
  const uniq = [...new Set(kinds)];
  return uniq.length ? { paint: uniq[0], also: uniq.slice(1).map((k) => PAINT_LABEL[k]) } : { paint: 'other', also: [] };
}

const readJson = (f) => (existsSync(f) ? JSON.parse(readFileSync(f, 'utf8')) : null);
const aliasOf = (v) => /^\{(.+)\}$/.exec(String(v))?.[1] ?? null;

function format(t, value) {
  if (typeof value === 'number') return t.$type === 'dimension' ? `${value}px` : String(value);
  if (Array.isArray(value)) return t.$type === 'cubicBezier' ? `cubic-bezier(${value.join(', ')})` : value.join(', ');
  if (value && typeof value === 'object') return value.value != null && value.unit ? `${value.value}${value.unit}` : JSON.stringify(value);
  return String(value);
}

export function generate({ root = process.cwd() } = {}) {
  const doc = readJson(join(root, 'extraction', 'tokens.json'));
  if (!doc || !Object.keys(doc.tokens ?? {}).length) return { error: 'no tokens in extraction/tokens.json — run the extraction first' };
  const decisions = readJson(join(root, 'extraction', 'decisions.json')) ?? {};
  const rename = new Map((decisions.tokens ?? []).filter((x) => x.name && x.name !== x.id).map((x) => [x.id, x.name]));
  const dropped = new Map();
  for (const x of decisions.excluded ?? []) if (!x.include) for (const k of x.tokens ?? []) dropped.set(k, `prototype-only: ${x.what ?? x.id}`);
  const problems = [], notes = [];  // problems fail gate 7; notes are consequences of the designer's decisions or of the app's own quirks
  const T = { ...doc.tokens };
  // values the designer approved (extraction/canon/decided.tokens.json, the format scripts/tokens.mjs reads): they fill a gap, never overwrite a measurement
  let approved = {};
  try { approved = readJson(join(root, 'extraction', 'canon', 'decided.tokens.json')) ?? {}; } catch (e) { problems.push(`extraction/canon/decided.tokens.json is not valid JSON: ${e.message}`); }
  const merged = [];
  for (const [key, t] of Object.entries(approved)) {
    if (key.startsWith('_') || !t || typeof t !== 'object') continue;
    if (T[key]?.$provenance?.label === 'measured') { problems.push(`${key} in decided.tokens.json would replace a value measured in the app — a decision fills a gap, never overwrites a measurement`); continue; }
    if (!['decided', 'derived'].includes(t.$provenance?.label) || !/\d{4}-\d{2}-\d{2}/.test(String(t.$provenance?.evidence ?? ''))) { problems.push(`${key} in decided.tokens.json needs label decided and dated evidence`); continue; }
    // a value that is neither a colour nor a shadow is filed by its role; with none (and none on the token it replaces) it would land in spacing
    if (!t.role && !T[key]?.$extensions?.[EXT]?.role && !['color', 'shadow'].includes(t.$type)) { problems.push(`${key} in decided.tokens.json needs a role (where the value is used: spacing, fontSize, …)`); continue; }
    // a key tokens.json holds as derived or decided: the approved value replaces it (as scripts/tokens.mjs does); said once, when it differs
    if (T[key] && String(T[key].$value) !== String(t.$value)) notes.push(`${key} in decided.tokens.json replaces the ${T[key].$provenance?.label ?? 'unlabelled'} value ${format(T[key], T[key].$value)} with ${format(t, t.$value)}`);
    else if (T[key]) continue; // the extraction already merged it
    const ref = aliasOf(t.$value);
    T[key] = { $type: t.$type, $value: t.$value, $provenance: { ...t.$provenance },
      $extensions: { [EXT]: { cssVar: T[key]?.$extensions?.[EXT]?.cssVar ?? `--${key}`, role: t.role ?? T[key]?.$extensions?.[EXT]?.role ?? (t.$type === 'color' ? 'color' : t.$type === 'shadow' ? 'shadow' : 'spacing'), css: ref ? `var(--${ref})` : typeof t.$value === 'number' ? `${t.$value}px` : String(t.$value), ...(t.$type === 'color' ? { cssForm: 'color' } : {}) } } };
    merged.push(key);
  }
  // an approved alias must point at a token that exists (after every approved value is in): else it is a problem and is not written
  for (const key of merged) {
    const ref = aliasOf(T[key].$value);
    if (ref && !T[ref]) { problems.push(`${key} in decided.tokens.json points at {${ref}}, which is not a token`); delete T[key]; }
  }
  // a '.' is not a CSS name character (the browser drops `--text-12.5px: …`): an extraction made before 0.1.4 proposed such
  // names, so they are written with '_' (--text-12_5px) and said in a note, and an older Workbench updates without a decision
  const rawName = (k) => rename.get(k) ?? String(T[k]?.$extensions?.[EXT]?.cssVar ?? `--${k}`).replace(/^--/, '');
  const nameOf = (k) => rawName(k).replace(/\./g, '_');
  // the product's own variable name -> token key (references in authored css use the old names), and the current names
  const byOld = new Map(), byName = new Map();
  for (const k of Object.keys(T)) { byOld.set(String(T[k].$extensions?.[EXT]?.cssVar ?? `--${k}`).replace(/^--/, ''), k); byOld.set(k, byOld.get(k) ?? k); byName.set(nameOf(k), byName.get(nameOf(k)) ?? k); }
  const keyOfVar = (n) => byName.get(n) ?? byOld.get(n) ?? null;
  // the designer's own exclusions, said once (the cascade below adds its own notes); only tokens that exist, by their current name
  const direct = [...dropped].filter(([k, why]) => why.startsWith('prototype-only:') && T[k]).map(([k]) => `--${nameOf(k)}`);
  if (direct.length) notes.push(`${direct.length} token(s) left out as prototype-only (the designer's decision): ${direct.join(', ')}`);
  // a token that refers to a dropped one is dropped too (reported), so nothing points at a variable that is not there
  let changed = true;
  while (changed) {
    changed = false;
    for (const [k, t] of Object.entries(T)) {
      if (dropped.has(k)) continue;
      const css = String(t.$extensions?.[EXT]?.css ?? '');
      const refs = [aliasOf(t.$value), aliasOf(t.$modes?.dark), ...[...css.matchAll(/var\(\s*--([A-Za-z0-9_-]+)/g)].map((m) => keyOfVar(m[1]))].filter(Boolean);
      const bad = refs.find((r) => dropped.has(r));
      if (bad) { dropped.set(k, `refers to a dropped token: ${bad}`); notes.push(`${k} refers to a dropped token (--${nameOf(bad)}): left out too`); changed = true; }
    }
  }
  const valueCss = (k, t, which = 'base') => {
    const x = t.$extensions?.[EXT] ?? {};
    const raw = which === 'dark' ? t.$modes?.dark : t.$value;
    const a = aliasOf(raw);
    if (a) return `var(--${nameOf(a)})`;
    if (which === 'base' && x.css && !/channels$/.test(x.cssForm ?? '')) {
      // a rename reaches the references inside the authored css too
      return String(x.css).replace(/var\(\s*--([A-Za-z0-9_-]+)/g, (m, n) => { const rk = byOld.get(n); return rk && rename.has(rk) ? `var(--${rename.get(rk)}` : m; });
    }
    return format(t, raw);
  };
  const usesOf = (t) => {
    const n = t.$provenance?.counters?.nodes, r = t.$extensions?.[EXT]?.usage?.rules;
    return n != null ? `on ${n} elements` : r ? `in ${r} style rules` : null;
  };
  let rows = [];
  for (const k of Object.keys(T).sort()) {
    if (dropped.has(k)) continue;
    const t = T[k], x = t.$extensions?.[EXT] ?? {};
    const first = rows.find((r) => r.name === nameOf(k));
    if (first) { problems.push(`two tokens are both named --${nameOf(k)}: ${first.key}, ${k}`); continue; }
    if (rawName(k) !== nameOf(k)) notes.push(`--${rawName(k)} is written as --${nameOf(k)}: a dot is not a CSS name character`);
    // any other character outside a CSS name (a space) is a problem: the browser would drop the declaration
    if (!/^[A-Za-z0-9_-]+$/.test(nameOf(k))) { problems.push(`--${nameOf(k)} is not a valid CSS custom property name (only letters, digits, - and _): rename it in extraction/decisions.json`); continue; }
    const group = GROUP_OF[x.role] ?? 'other';
    const renamedFrom = rename.has(k) ? k : undefined;
    const label = t.$provenance?.label ?? 'unknown';
    if (!['measured', 'derived', 'decided'].includes(label)) problems.push(`${k} has no label (measured / derived / decided)`);
    const proposed = label !== 'decided' && !t.$provenance?.authoredName;
    const dark = t.$modes?.dark != null && t.$modes.dark !== t.$value ? valueCss(k, t, 'dark') : undefined;
    const paints = x.role === 'color' ? paintOf(x.usage?.props, String(t.$provenance?.evidence ?? '')) : null;
    rows.push({ key: k, name: nameOf(k), cssVar: `--${nameOf(k)}`, group, role: x.role ?? 'other', value: valueCss(k, t), dark, label,
      roleLabel: x.roleProvenance?.label, evidence: String(t.$provenance?.evidence ?? '').slice(0, 300), uses: usesOf(t) ?? undefined, renamedFrom, proposed,
      ...(paints ? { paint: paints.paint, also: paints.also } : {}) });
  }
  // A custom property that refers to itself (the next/font pattern `--font-sans: var(--font-sans)`) or sits on a var()
  // cycle is invalid at computed-value time and the browser drops it: it gets its concrete value, or is left out when there is none.
  const concrete = (key, which) => {
    const seen = new Set();
    for (let k = key; ; ) {
      if (seen.has(k)) return null;
      seen.add(k);
      const t = T[k], raw = which === 'dark' ? (t.$modes?.dark ?? t.$value) : t.$value, a = aliasOf(raw);
      if (!a) return format(t, raw);
      if (!T[a]) return `var(--${nameOf(a)})`;
      k = a;
    }
  };
  const refsOf = (r) => new Set([...`${r.value} ${r.dark ?? ''}`.matchAll(/var\(\s*--([A-Za-z0-9_-]+)/g)].map((m) => m[1]));
  const byRow = new Map(rows.map((r) => [r.name, r]));
  const out = new Map();
  const leaveOut = (r, reason) => { out.set(r.name, r); dropped.set(r.key, reason); };
  const settle = (r) => {
    const value = concrete(r.key, 'base'), dark = r.dark ? concrete(r.key, 'dark') : undefined;
    if (value == null || (r.dark && dark == null)) return false;
    r.value = value; if (r.dark) r.dark = dark;
    return true;
  };
  const CYCLE = 'cycle in token references with no concrete value';
  for (const r of rows) if (refsOf(r).has(r.name) && !settle(r)) { leaveOut(r, CYCLE); notes.push(`cycle in token references: --${r.name} → --${r.name} (no concrete value)`); }
  const done = new Set(), onPath = [];
  const walk = (r) => {
    if (done.has(r.name)) return;
    const at = onPath.indexOf(r.name);
    if (at > -1) {
      const loop = onPath.slice(at);
      const ok = loop.map((n) => (out.has(n) ? false : settle(byRow.get(n))));
      loop.forEach((n, i) => { if (!out.has(n) && !ok[i]) leaveOut(byRow.get(n), CYCLE); });
      notes.push(`cycle in token references: ${[...loop, r.name].map((n) => `--${n}`).join(' → ')} (${ok.every(Boolean) ? 'resolved values used' : 'no concrete value'})`);
      return;
    }
    onPath.push(r.name);
    for (const n of refsOf(r)) if (byRow.has(n) && n !== r.name) walk(byRow.get(n));
    onPath.pop();
    done.add(r.name);
  };
  for (const r of rows) walk(r);
  // whatever still points at a token that was left out is settled the same way, until nothing changes
  for (let again = true; again; ) {
    again = false;
    for (const r of rows) {
      if (out.has(r.name)) continue;
      const bad = [...refsOf(r)].find((n) => out.has(n));
      if (!bad) continue;
      if (!settle(r) || [...refsOf(r)].some((n) => out.has(n))) {
        leaveOut(r, `refers to a token with no concrete value: ${out.get(bad).key}`);
        notes.push(`${r.key} refers to a token with no concrete value (--${bad}): left out too`);
      }
      again = true;
    }
  }
  rows = rows.filter((r) => !out.has(r.name));
  const comment = (r) => [r.label, r.uses, r.proposed ? (r.renamedFrom ? `proposed name ${r.renamedFrom}, renamed by the designer` : 'proposed name') : null].filter(Boolean).join(' · ');
  const files = {};
  const present = GROUPS.filter((g) => rows.some((r) => r.group === g));
  for (const g of present) {
    const rs = rows.filter((r) => r.group === g);
    const lines = [HEADER, ':root {', ...rs.map((r) => `  ${r.cssVar}: ${r.value}; /* ${comment(r)} */`), '}'];
    const darks = rs.filter((r) => r.dark);
    if (darks.length) {
      const body = darks.map((r) => `    ${r.cssVar}: ${r.dark};`);
      lines.push('', '@media (prefers-color-scheme: dark) {', '  :root:not([data-theme="light"]) {', ...body, '  }', '}', '', ':root[data-theme="dark"] {', ...body.map((l) => l.slice(2)), '}');
    }
    files[`src/tokens/${g}.css`] = lines.join('\n') + '\n';
  }
  const cv = doc.$meta?.platform?.canvas;
  // a canvas part that names no token still uses one when exactly one token of that role holds exactly that value
  const px = (s) => { const m = /^(-?[\d.]+)(px)?$/.exec(String(s).trim()); return m ? String(Number(m[1])) : null; };
  const CANON = { color: (s) => { const c = parseColor(s); return c ? toHex(c) : null; }, fontSize: px, lineHeight: px, fontWeight: (s) => (/^\d+$/.test(String(s).trim()) ? String(Number(s)) : null),
    fontFamily: (s) => String(s).toLowerCase().replace(/["']/g, '').replace(/\s+/g, ' ').trim() || null };
  const holders = (role, value) => {
    const want = CANON[role]?.(value);
    if (want == null) return [];
    return rows.filter((r) => r.role === role && CANON[role](concrete(r.key, 'base')) === want);
  };
  const decl = (prop, part, role) => {
    if (!part) return null;
    if (part.token && !dropped.has(part.token) && T[part.token]) return `  ${prop}: var(--${nameOf(part.token)});`;
    const hit = part.value && role ? holders(role, part.value) : [];
    if (hit.length === 1) return `  ${prop}: var(--${hit[0].name});`;
    if (hit.length > 1) return `  ${prop}: ${part.value}; /* two or more tokens hold it — choose one: ${hit.map((h) => `--${h.name}`).join(', ')} */`;
    return part.value ? `  ${prop}: ${part.value}; /* measured, no token holds it */` : null;
  };
  files['src/tokens/canvas.css'] = [HEADER, '/* <body> as the product paints it (computed style, most common over the captured screens) */', 'body {',
    ...[decl('background-color', cv?.background, 'color'), decl('color', cv?.color, 'color'), decl('font-family', cv?.fontFamily, 'fontFamily'), decl('font-size', cv?.fontSize, 'fontSize'), decl('line-height', cv?.lineHeight, 'lineHeight'), decl('font-weight', cv?.fontWeight, 'fontWeight')].filter(Boolean), '}'].join('\n') + '\n';
  // The web fonts the app loads (tokens.mjs: $meta.platform.fonts), so text in the Workbench is measured in them.
  const unq = (v) => String(v ?? '').trim().replace(/^["']|["']$/g, '');
  const wf = doc.$meta?.platform?.fonts;
  const sheets = wf?.stylesheets ?? [], faces = wf?.faces ?? [];
  const hasFonts = sheets.length > 0 || faces.length > 0;
  if (hasFonts) {
    files['src/tokens/fonts.css'] = [HEADER, '/* the web fonts the app loads (captured) */',
      ...sheets.map((h) => `@import url("${h}");`),
      ...faces.map((f) => ['@font-face {', `  font-family: "${unq(f.family)}";`, f.weight ? `  font-weight: ${f.weight};` : null, f.style ? `  font-style: ${f.style};` : null, f.unicodeRange ? `  unicode-range: ${f.unicodeRange};` : null, `  src: ${f.src};`, '  font-display: swap;', '}'].filter(Boolean).join('\n'))].join('\n') + '\n';
  }
  // a used family that no stylesheet names and no face declares: nothing recorded would load it. A stylesheet whose
  // url names no family (a kit id, a css file) is opaque and counts as covering every family.
  const sheetFamilies = sheets.map((h) => { const m = [...String(h).matchAll(/[?&]family=([^&]+)/g)]; return m.length ? m.map((x) => decodeURIComponent(x[1].replace(/\+/g, ' ')).split(':')[0].toLowerCase()) : null; });
  const covered = (family) => faces.some((f) => unq(f.family).toLowerCase() === family.toLowerCase()) || sheetFamilies.some((fam) => fam === null || fam.includes(family.toLowerCase()));
  const seenUse = new Set();
  for (const u of wf?.used ?? []) {
    const family = unq(u.family), k = `${family}|${u.weight}`;
    if (!family || seenUse.has(k) || covered(family)) continue;
    seenUse.add(k);
    notes.push(`the app uses ${family} ${u.weight} but no font source was captured — text widths in parity may differ (NEEDS-FONT)`);
  }
  files['src/tokens/index.css'] = [HEADER, ...(hasFonts ? ["@import './fonts.css';"] : []), ...present.map((g) => `@import './${g}.css';`), "@import './canvas.css';"].join('\n') + '\n';
  // The composite text styles the app really uses: (family, size, weight, line height, letter spacing) of every element with
  // its own text in the light captures, counted, with one interface text of the app as the example and the tokens that build it.
  const textStyles = (() => {
    const dir = join(root, 'extraction', 'baseline');
    let files = [];
    try { files = readdirSync(dir).filter((f) => f.endsWith('.json')); } catch { return []; }
    const flow = (readJson(join(root, 'extraction', 'flows', 'flows.json'))?.screens ?? []).map((s) => s.name);
    const caps = [];
    for (const f of files) {
      let c; try { c = JSON.parse(readFileSync(join(dir, f), 'utf8')); } catch { continue; }
      if ((c.meta?.colorScheme ?? (/--dark\.json$/.test(f) ? 'dark' : 'light')) !== 'light') continue;
      caps.push({ screen: c.meta?.screen ?? f.replace(/--.*$/, ''), elements: Array.isArray(c.elements) ? c.elements : [] });
    }
    const rank = (c) => { const i = flow.indexOf(c.screen); return i < 0 ? flow.length : i; };
    caps.sort((a, b) => rank(a) - rank(b) || String(a.screen).localeCompare(String(b.screen)));
    const num = (v) => { const m = /^(-?[\d.]+)px$/.exec(String(v ?? '').trim()); return m ? Math.round(Number(m[1]) * 100) / 100 : null; };
    // interface text (a label, a heading) and not data: short, no email / link / number-like content, not a table cell
    const isInterface = (t, path) => t.length >= 2 && t.length <= 40 && !/@|https?:|www\./.test(t) && (t.match(/\d/g) ?? []).length <= t.length * 0.25 && /\p{L}{2}/u.test(t) && !/(^|>)(td|tbody)\b/.test(path ?? '');
    const styles = new Map();
    for (const c of caps) for (const e of c.elements) {
      const text = String(e.text ?? '').replace(/\s+/g, ' ').trim(), v = e.values ?? {};
      if (!text || num(v.fontSize) == null) continue;
      const lh = v.lineHeight === 'normal' || v.lineHeight == null ? 'normal' : num(v.lineHeight);
      const ls = v.letterSpacing === 'normal' || v.letterSpacing == null || num(v.letterSpacing) === 0 ? 'normal' : num(v.letterSpacing);
      if (lh == null || ls == null) continue;
      const familyCss = String(v.fontFamily ?? '').trim(), weight = Number(v.fontWeight) || 400;
      const key = [familyCss, num(v.fontSize), weight, lh, ls].join('|');
      const s = styles.get(key) ?? { family: unq(familyCss.split(',')[0]), familyCss, size: num(v.fontSize), weight, lineHeight: lh, letterSpacing: ls, uses: 0, example: undefined };
      s.uses += 1;
      if (s.example == null && isInterface(text, e.path)) s.example = text;
      styles.set(key, s);
    }
    const near = (a, b) => Math.abs(a - b) < 0.011;
    const tokenFor = (role, test) => rows.find((r) => r.role === role && test(concrete(r.key, 'base')))?.cssVar ?? null;
    return [...styles.values()].sort((a, b) => a.size - b.size || a.weight - b.weight || b.uses - a.uses).map((s) => {
      const tokens = {
        fontFamily: tokenFor('fontFamily', (v) => CANON.fontFamily(v) === CANON.fontFamily(s.familyCss)),
        fontSize: tokenFor('fontSize', (v) => px(v) != null && near(Number(px(v)), s.size)),
        fontWeight: tokenFor('fontWeight', (v) => CANON.fontWeight(v) === String(s.weight)),
      };
      // a token holds the line height as px, or as a plain ratio of the size; letter spacing as px or em
      if (s.lineHeight !== 'normal') tokens.lineHeight = tokenFor('lineHeight', (v) => (/px$/.test(String(v)) ? near(parseFloat(v), s.lineHeight) : /^[\d.]+$/.test(String(v)) && near(Number(v) * s.size, s.lineHeight)));
      if (s.letterSpacing !== 'normal') tokens.letterSpacing = tokenFor('letterSpacing', (v) => (/px$/.test(String(v)) ? near(parseFloat(v), s.letterSpacing) : /em$/.test(String(v)) && near(parseFloat(v) * s.size, s.letterSpacing)));
      return { ...s, tokens };
    });
  })();
  const product = doc.$meta?.product ?? 'Product';
  const when = String(readJson(join(root, 'extraction', 'capture-manifest.json'))?.createdAt ?? doc.$meta?.extractedAt ?? '').slice(0, 10);
  files['src/tokens/tokens.json'] = JSON.stringify({ _generated: 'by tools/tokens-css.mjs — do not edit (npm run check:tokens)', product, themes: { dark: rows.some((r) => r.dark) },
    tokens: rows.map(({ proposed, ...r }) => r), textStyles, dropped: [...dropped].map(([key, reason]) => ({ key, reason })) }, null, 1) + '\n';
  const plain = (x) => String(x).replace(/[{}<>`\\]/g, '');
  files['src/foundations/Overview.mdx'] = [
    '{/* Generated by tools/tokens-css.mjs — do not edit (npm run check:tokens) */}',
    "import { Meta } from '@storybook/addon-docs/blocks';",
    '',
    '<Meta title="Foundations/Overview" />',
    '',
    `# ${plain(product)} design system`,
    '',
    `This Workbench holds the design system of ${plain(product)}, taken from the live app${when ? ` on ${when}` : ''}. Where it was captured and with which tool: PROJECT.md and extraction/capture-manifest.json.`,
    '',
    '## How to read a value',
    '',
    'Every value says how it was obtained. Hover the label for the evidence.',
    '',
    '- **measured**: read from the app, as the browser computed it.',
    '- **derived**: computed from what the app paints, for example a colour the app uses outside its own tokens.',
    '- **decided**: a person decided it. The evidence names who and when.',
    '',
    '## Structure',
    '',
    '- **Foundations**: colours, text styles, spacing, radius and the other tokens.',
    '- **Components**: built only from those tokens.',
    '- **Screens**: built from the components.',
    '',
    '## Tokens are generated',
    '',
    'Tokens come from extraction/tokens.json through `npm run tokens`. Never edit them by hand: `npm run check:tokens` fails on a hand edit. A value a designer approves goes into extraction/canon/decided.tokens.json.',
  ].join('\n') + '\n';
  const imports = ["import type { Meta, StoryObj } from '@storybook/react-vite';", "import { TokenTable } from './TokenTable';"];
  files['src/foundations/Foundations.stories.tsx'] = [
    '// Generated by tools/tokens-css.mjs — do not edit (npm run check:tokens)',
    ...imports,
    '',
    "// no component and no story arguments: the pages are read-only, so Storybook shows no controls",
    "const meta = { title: 'Foundations/Tokens', parameters: { controls: { disable: true }, actions: { disable: true } } } satisfies Meta;",
    'export default meta;',
    'type Story = StoryObj;',
    '',
    ...present.map((g) => `export const ${STORY[g]}: Story = { render: () => <TokenTable group="${g}" /> };`),
  ].join('\n') + '\n';
  return { files, problems, notes, product };
}

const isMain = (() => { try { return realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url)); } catch { return false; } })();
